#!/usr/bin/env python3
"""Curate source/evidence into verified independently extractable ZIPs under8MB.

Original binaries, mapped images/Ghidra databases, upstream dependencies and
large unreviewed candidate caches remain in the workspace. Current targeted C
exports and separately labeled prior C exports are retained in full.
"""
import argparse,csv,hashlib,json,shutil,zipfile,zlib
from collections import defaultdict
from pathlib import Path
ap=argparse.ArgumentParser();ap.add_argument('root',type=Path);ap.add_argument('output',type=Path);ap.add_argument('--prior-decomp',action='append',default=[],help='label=/path/to/previous/DECOMPILATION');a=ap.parse_args();root=a.root.resolve();out=a.output.resolve();assert root!=out and root not in out.parents,'Output must be outside source project';out.mkdir(parents=True,exist_ok=True);stage=out/'staging'/'bedrock_anticheat_final_1.26.52.3'
if stage.exists()and any(stage.iterdir()):
 assert(stage/'PACKAGE_README.md').is_file(),'Refusing to replace unrecognized staging data'
 shutil.rmtree(stage)
stage.mkdir(parents=True,exist_ok=True)
suffixes={'.md','.txt','.csv','.dot','.svg','.h','.c','.cpp','.java','.py','.sh','.patch','.json','.log','.tsv','.s','.asm','.xml'}
omitted=[];copied=[]
def sha(p):return hashlib.file_digest(p.open('rb'),'sha256').hexdigest()
def reason(p):
 rel=p.relative_to(root);s=rel.as_posix();parts=rel.parts
 if '__pycache__'in parts or '.git'in parts:return'generated bytecode or repository internals'
 if s.startswith(('WORK/geyser/upstream/','WORK/input/vendor/','WORK/history_writer/allocation_candidates/','WORK/catalog_cache/')):return'upstream dependency, regenerable cache, or broad unreviewed allocation candidates'
 if p.name.endswith('.pdata.bin'):return'regenerable unwind cache'
 if s=='WORK/collision/name_strings.json':return'large unreviewed string-candidate cache; not a cited evidence source'
 if s.startswith('JAVA/build/'):
  if p.parent==root/'JAVA/build' and(p.name in ['bedrock-movement-research-core.jar','bedrock-movement-geyser-adapter.jar']or p.name.endswith('verification.json')):return''
  return'generated build intermediates'
 if 'build'in parts and s.startswith('JAVA/'):return'generated kernel build intermediates'
 if p.suffix.lower()not in suffixes:return'binary/dependency or non-source intermediate'
 return''
for p in sorted(root.rglob('*')):
 if not p.is_file():continue
 why=reason(p);rel=p.relative_to(root)
 if why:
  omitted.append({'path':str(rel),'bytes':p.stat().st_size,'sha256':sha(p),'reason':why});continue
 dest=stage/rel;dest.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(p,dest);copied.append(str(rel))
prior=[]
for spec in a.prior_decomp:
 label,path=spec.split('=',1);base=Path(path)
 for p in sorted(base.rglob('*.c')):
  rel=Path('PRIOR_GHIDRA_EXPORTS')/label/p.relative_to(base);dest=stage/rel;dest.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(p,dest);prior.append({'retained':str(rel),'source':str(p),'bytes':p.stat().st_size,'sha256':sha(p),'status':'historical export; no new independent semantic review implied'})
def csvwrite(p,rows,fields):
 p.parent.mkdir(parents=True,exist_ok=True)
 with p.open('w',newline='')as f:
  w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(rows)
csvwrite(stage/'DATA/OMITTED_ARTIFACTS.csv',omitted,['path','bytes','sha256','reason'])
csvwrite(stage/'PRIOR_GHIDRA_EXPORTS/MANIFEST.csv',prior,['retained','source','bytes','sha256','status'])
(stage/'PRIOR_GHIDRA_EXPORTS/README.md').write_text('# Historical Ghidra exports\n\nAll .c exports found under the explicitly supplied previous project directories are retained, with source paths and hashes in MANIFEST.csv. They supplement the current DECOMPILATION collection and are not automatically confirmed current findings. Full proprietary mapped images/databases are excluded; a fresh import can be generated from the separately supplied original EXE using the included mapper/instructions.\n')
(stage/'PACKAGE_README.md').write_text('# Research delivery\n\nRead README.md and CHECKPOINT_SUMMARY.md first. This is an incomplete native research/Java port checkpoint. All current targeted Ghidra C exports and all supplied prior project .c exports are included; this source tree is not a whole-executable decompilation or a raw Ghidra database.\n\nThe numbered research packages are valid independent ZIPs; extract all into the same directory. No binary concatenation is needed. The project root is bedrock_anticheat_final_1.26.52.3. Each ZIP is below 8,000,000 bytes. The separately published earlier Ghidra project snapshot has its own restore instructions; this delivery does not replace that raw database.\n\nOriginal server EXE, standalone mapped image, upstream Geyser JAR/repository, Python vendor packages and large unreviewed candidate caches are excluded. The raw database is not part of this source tree. DATA/OMITTED_ARTIFACTS.csv records source-tree omissions; all originals remain in the workspace. Install SCRIPTS/requirements.txt and supply the verified original EXE to regenerate native oracle results.\n\nSOURCE_FILE_MANIFEST.csv covers retained files except itself; archive hashes/CRC results are recorded in the external download manifest. Parts1-6 remain the exact prefix of the consolidated TXT, verified by DATA/CONSOLIDATION_VERIFICATION.json.\n')
rows=[];duplicates=defaultdict(list)
for p in sorted(stage.rglob('*')):
 if not p.is_file()or p.name=='SOURCE_FILE_MANIFEST.csv':continue
 rel=str(p.relative_to(stage));digest=sha(p);rows.append({'path':rel,'bytes':p.stat().st_size,'sha256':digest});duplicates[digest].append(rel)
csvwrite(stage/'SOURCE_FILE_MANIFEST.csv',rows,['path','bytes','sha256'])
# Check the evidence paths in the staged result, after omission decisions.
missing=[]
for row in csv.DictReader((stage/'EVIDENCE.csv').open()):
 if not(stage/row['source_artifact']).is_file():missing.append(row['source_artifact'])
for row in csv.DictReader((stage/'FUNCTION_INDEX.csv').open()):
 for field in ['assembly','decompilation']:
  for name in row[field].split(';'):
   if name and not(stage/name).is_file():missing.append(name)
assert not missing,sorted(set(missing))
items=sorted((p for p in stage.rglob('*')if p.is_file()),key=lambda p:(p.relative_to(stage).parts[0]in ['ASSEMBLY','WORK','PRIOR_GHIDRA_EXPORTS'],str(p.relative_to(stage))))
groups=[];current=[];estimate=0;limit=7_700_000
for p in items:
 data=p.read_bytes();c=zlib.compressobj(9,zlib.DEFLATED,-15);n=len(c.compress(data)+c.flush())+2*len(str(p.relative_to(stage)))+300
 if current and estimate+n>limit:groups.append(current);current=[];estimate=0
 assert n<limit,('One entry requires splitting',str(p),n)
 current.append(p);estimate+=n
if current:groups.append(current)
archives=[]
for n,group in enumerate(groups,1):
 name='bedrock_movement_research_checkpoint_1.26.52.3.zip'if len(groups)==1 else f'{n}.zip';target=out/name
 with zipfile.ZipFile(target,'w',zipfile.ZIP_DEFLATED,compresslevel=9)as z:
  for p in group:z.write(p,str(Path(stage.name)/p.relative_to(stage)))
 assert target.stat().st_size<8_000_000
 with zipfile.ZipFile(target)as z:
  assert z.testzip()is None
  for p in group:assert hashlib.sha256(z.read(str(Path(stage.name)/p.relative_to(stage)))).hexdigest()==sha(p)
 archives.append({'file':name,'bytes':target.stat().st_size,'sha256':sha(target),'entries':len(group),'crc_verified':True,'contents_sha256_verified':True})
readable=[]
for name in ['READABLE_SIMULATION_VALIDATION.json','ENVIRONMENT_STAGES_VALIDATION.json','NATIVE_SHAPES_VALIDATION.json']:
 p=stage/'DATA'/name
 if not p.exists():continue
 d=json.loads(p.read_text());assert d['mismatches']==0,(name,d['mismatches'])
 for source,digest in d['sources'].items():
  assert(stage/source).is_file()and sha(stage/source)==digest,('Stale native comparison source',name,source)
 readable.append({'report':'DATA/'+name,'case_count':d['case_count'],'variants':len(d['cases_by_variant']),'mismatches':d['mismatches'],'nan_payload_differences':d['nan_payload_differences'],'source_hashes_verified':True})
record={'project_folder':stage.name,'archives':archives,'file_count':len(items),'current_targeted_ghidra_c':len(list((stage/'DECOMPILATION').rglob('*.c'))),'historical_ghidra_c':len(prior),'omitted_files':len(omitted),'omitted_bytes':sum(x['bytes']for x in omitted),'missing_evidence_paths':missing,'full_simulator_status':'incomplete; Unavailable','numeric_machine_cases':json.loads((stage/'DATA/verification_summary.json').read_text())['total_machine_comparison_cases'],'readable_cpp_suites':readable,'readable_cpp_machine_cases':sum(x['case_count']for x in readable),'readable_cpp_variants':sum(x['variants']for x in readable),'duplicate_groups':{h:p for h,p in duplicates.items()if len(p)>1}}
(out/'DOWNLOAD_MANIFEST.json').write_text(json.dumps(record,indent=2)+'\n');print(json.dumps({k:v for k,v in record.items()if k!='duplicate_groups'},indent=2))
